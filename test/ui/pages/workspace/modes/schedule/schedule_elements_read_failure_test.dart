/// A router manager whose [pop] does nothing: these bloc tests don't build a real GoRouter.
class _SilentRouterManager extends OcptRouterManager {
  /// Ignore the pop: this double navigates nowhere.
  @override
  void pop<Y extends Object?>([Y? result]) {}
}

/// What the schedule mode does when it cannot read the elements catalogue it is loaded with: it
/// stops before it emits anything, and loads once it can be read.
void main() {
  late OcptPropertiesManager propertiesManager;
  late OcptProjectsManager projectsManager;
  late Directory tempDir;

  setUpAll(() async {
    OcptGlobalManager.instance;

    SharedPreferencesAsyncPlatform.instance = InMemorySharedPreferencesAsync.empty();
    propertiesManager = OcptPropertiesManager();
    await propertiesManager.initLifeCycle();
  });

  setUp(() async {
    tempDir = await Directory.systemTemp.createTemp("ocpt_schedule_elements_read_test_");
    projectsManager = OcptProjectsManager(
      propertiesManager: propertiesManager,
      appLanguageCode: () => "en",
    );
    await projectsManager.initLifeCycle();
    final result = await projectsManager.createProject(
      name: "My Movie",
      filePath: p.join(tempDir.path, "movie.ocpt"),
    );
    expect(result.status.isSuccess, isTrue);
  });

  tearDown(() async {
    await projectsManager.disposeLifeCycle();
    await tempDir.delete(recursive: true);
  });

  /// Build a mode bloc on the test project.
  OcptScheduleBloc buildMode() => OcptScheduleBloc(
    projectsManager: projectsManager,
    propertiesManager: propertiesManager,
    routerManager: _SilentRouterManager(),
    exportManager: OcptExportManager(fileSelectorManager: const FileSelectorManager()),
  );

  test("the mode stays loading while the elements cannot be read", () async {
    final database = projectsManager.currentProject!.database;
    await database.customStatement("ALTER TABLE elements RENAME TO elements_gone");

    final mode = buildMode();
    addTearDown(mode.close);
    await Future<void>.delayed(const Duration(milliseconds: 500));

    expect(mode.state.isLoading, isTrue);
  });

  test("the mode loads once they can be read", () async {
    final mode = buildMode();
    addTearDown(mode.close);

    await mode.stream.firstWhere((state) => !state.isLoading).timeout(const Duration(seconds: 5));
  });
}
